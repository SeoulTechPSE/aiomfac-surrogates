def desc(o, mgs=MGS):
    c, tq = np.zeros(len(mgs)), 0
    for s, q in o["subgroups"]:
        c[mgs.index(_sg.main_group(int(s)))] += q; tq += q
    return [*(c / max(tq, 1)), o["oc"], o["nc"], np.log(o["M"]), np.log1p(tq)]


