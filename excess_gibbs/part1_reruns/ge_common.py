"""Shared data and the excess-Gibbs-energy (G^E) head for the Part 1 re-runs with thermodynamically consistent
surrogates.

Molecules, labels and splits are those of aiomfac-surrogates v2.0.1, part1_organic_surrogate (notebook 01: pool,
hash split, label set of 20 water mass fractions x 4 temperatures; notebook 08: label set of 10 x 3 for Table 3),
regenerated by research/paper_5/code/s1_data.py (label set 1, identical sampling) and here (label set 2, synthetic
pretraining labels).

G^E head: for any molecular feature vector f, the network outputs h(f, w, T) (SiLU MLP) and
    g = G^E/(RT n) = x_w x_o h,  ln gamma_w = g - x_o dg/dx_o,  ln gamma_org = g + x_w dg/dx_o
(autograd; x_o is the organic mole fraction, w the water mass fraction w(x_o; M) with the AIOMFAC molar mass M of the
organic).  Gibbs-Duhem and the pure-component reference states hold by construction.
"""
